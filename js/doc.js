MTF.buildDocData = function (state, res) {
  const p = state.params;
  const f = MTF.fmt;
  const last = res.herd[res.herd.length - 1];
  const capacityCows = p.capacity.cowPlaces + p.capacity.dryPlaces;

  const feeText = p.finance.operatorFeeMode === 'revenue'
    ? p.finance.operatorFeeValue + '% от выручки'
    : p.finance.operatorFeeMode === 'ebitda'
      ? p.finance.operatorFeeValue + '% от EBITDA'
      : f.num(p.finance.operatorFeeValue) + ' тыс. ₸ в год';

  return {
    region: p.project.region || '__________',
    district: p.project.district || '__________',
    operator: p.project.operator || '__________',
    farmsCount: p.project.farmsCount,
    startYear: p.project.startYear,
    endYear: p.project.startYear + p.project.horizon - 1,
    horizon: p.project.horizon,
    capacityCows: capacityCows,
    totalCows: capacityCows * p.project.farmsCount,
    cowPlaces: p.capacity.cowPlaces,
    dryPlaces: p.capacity.dryPlaces,
    calfPlaces: p.capacity.calfPlaces,
    heiferPlaces: p.capacity.heiferPlaces,
    startHeifers: p.herd.startHeifers,
    batches: p.herd.batches,
    batchInterval: p.herd.batchInterval,
    milkYield: f.num(p.production.milkYield),
    calvingRate: p.production.calvingRate,
    cullRate: p.production.cullRate,
    breed: p.herd.breed,
    source: p.herd.source,
    remontModeText: MTF.remontModeText[p.production.remontMode],
    operatorFeeText: feeText,
    cowsAtCapacity: f.num(Math.round(last.cows)),
    heifersAtCapacity: f.num(Math.round(last.heifers)),
    totalAtCapacity: f.num(Math.round(last.total))
  };
};

MTF.renderDoc = function (state, res) {
  const data = MTF.buildDocData(state, res);
  const tables = MTF.docTables(state, res);
  Object.assign(data, tables);

  return state.docSections.filter(s => s.enabled).map(s => {
    let body = s.body;
    Object.keys(data).forEach(k => {
      body = body.split('{{' + k + '}}').join(data[k]);
    });
    return { title: s.title, body: body };
  });
};
